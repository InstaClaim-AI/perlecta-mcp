def largeurs_standard(base: str) -> dict[int, float]:
    """Largeurs d'une police standard sans /Widths, vide si elle n'est pas connue."""
    nom = base.lstrip("/").split("+")[-1]
    nom = _ALIAS_STANDARD.get(nom, nom)
    if nom.startswith("Courier"):
        return {code: 0.6 for code in range(32, 256)}
    valeurs = _LARGEURS_STANDARD.get(nom)
    if valeurs is None:
        return {}
    return {32 + i: v / 1000.0 for i, v in enumerate(valeurs) if v}


