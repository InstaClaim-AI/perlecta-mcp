"""Polices et decodage du texte des flux de contenu PDF.

Le texte montre par Tj et TJ est une suite de codes propres a la police. Le
decodage vers Unicode suit, par ordre de fiabilite : la table ToUnicode de la
police, puis l'encodage declare (WinAnsi, c'est-a-dire cp1252, ou MacRoman),
puis une approximation en cp1252. Chaque segment porte la fiabilite de son
decodage : les detecteurs qui raisonnent sur les points de code ne lisent que
les segments decodes de facon fiable.

latin-1 n'est pas WinAnsi : les polices standard utilisent cp1252, ou les
octets 0x80 a 0x9F portent le tiret cadratin, les guillemets et l'euro.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any

MAPPAGES_MAX = 200_000
CODES_MAX_PAR_PLAGE = 65_536

_JETON = re.compile(
    rb"<([0-9A-Fa-f\s]*)>"  # chaine hexadecimale
    rb"|(\[|\])"  # tableau
    rb"|(/[^\s/\[\]<>(){}%]*)"  # nom
    rb"|([+-]?\d+(?:\.\d+)?)"  # nombre
    rb"|([A-Za-z][A-Za-z0-9]*)"  # mot-cle
    rb"|%[^\r\n]*"  # commentaire
)


@dataclass
class Police:
    """Ce qu'il faut d'une police pour decoder et mesurer le texte qu'elle montre."""

    nom: str
    octets_par_code: tuple[int, ...] = (1,)
    plages: tuple[tuple[int, int, int], ...] = ()
    tounicode: dict[int, str] | None = None
    encodage: str | None = "cp1252"
    decodage_defaut: str = "approx"
    largeurs: dict[int, float] = field(default_factory=dict)
    largeur_defaut: float = 0.55
    type3: bool = False

    def codes(self, octets: bytes) -> list[int]:
        """Decoupe la chaine en codes selon les plages de codes de la police."""
        longueurs = sorted(set(self.octets_par_code)) or [1]
        resultat: list[int] = []
        i, n = 0, len(octets)
        while i < n:
            choisi: tuple[int, int] | None = None
            for longueur in longueurs:
                if i + longueur > n:
                    continue
                code = int.from_bytes(octets[i : i + longueur], "big")
                if not self.plages or any(
                    nb == longueur and bas <= code <= haut for nb, bas, haut in self.plages
                ):
                    choisi = (longueur, code)
                    break
            if choisi is None:
                longueur = min(longueurs[0], n - i)
                choisi = (longueur, int.from_bytes(octets[i : i + longueur], "big"))
            resultat.append(choisi[1])
            i += choisi[0]
        return resultat

    def decoder(self, octets: bytes) -> tuple[str, str, list[int]]:
        """Rend (texte, fiabilite du decodage, codes).

        Fiabilite : tounicode, winansi, macroman, approx ou inconnu.
        """
        codes = self.codes(octets)
        if self.tounicode is not None:
            morceaux: list[str] = []
            manquants = 0
            for code in codes:
                texte = self.tounicode.get(code)
                if texte is None:
                    manquants += 1
                    texte = self._repli(code)
                morceaux.append(texte)
            return "".join(morceaux), ("approx" if manquants else "tounicode"), codes
        if self.encodage:
            return (
                bytes(c & 0xFF for c in codes).decode(self.encodage, errors="replace"),
                self.decodage_defaut,
                codes,
            )
        return "", "inconnu", codes

    def _repli(self, code: int) -> str:
        if self.encodage and code < 256:
            return bytes([code]).decode(self.encodage, errors="replace")
        return ""

    def largeur(self, code: int) -> float:
        """Largeur du glyphe en unites de texte (1 = taille de police)."""
        return self.largeurs.get(code, self.largeur_defaut)


def _hex(brut: bytes) -> bytes:
    propre = re.sub(rb"\s+", b"", brut)
    if len(propre) % 2:
        propre += b"0"
    try:
        return bytes.fromhex(propre.decode("ascii"))
    except ValueError:
        return b""


def _texte_utf16(octets: bytes) -> str:
    if len(octets) == 1:
        return chr(octets[0])
    return octets.decode("utf-16-be", errors="replace")


def _incrementer(texte: str, decalage: int) -> str:
    if not texte:
        return ""
    point = ord(texte[-1]) + decalage
    if point < 0 or point > 0x10FFFF:
        return texte
    if 0xD800 <= point <= 0xDFFF:
        # une demi-paire de substitution n'est pas un caractere : la serialiser
        # en UTF-8 echouerait, et ferait perdre tout le rapport
        return texte[:-1] + "\ufffd"
    return texte[:-1] + chr(point)


def analyser_cmap(octets: bytes) -> tuple[dict[int, str], list[tuple[int, int, int]]]:
    """Lit une table ToUnicode : mappages code -> texte et plages de codes.

    Lecture tolerante : une table malformee rend ce qui a pu etre lu. Les
    volumes sont plafonnes, une table ne peut pas faire exploser la memoire.
    """
    jetons: list[tuple[str, bytes]] = []
    for m in _JETON.finditer(octets):
        if m.group(1) is not None:
            jetons.append(("hex", m.group(1)))
        elif m.group(2) is not None:
            jetons.append(("crochet", m.group(2)))
        elif m.group(3) is not None:
            jetons.append(("nom", m.group(3)))
        elif m.group(4) is not None:
            jetons.append(("nombre", m.group(4)))
        elif m.group(5) is not None:
            jetons.append(("mot", m.group(5)))
        if len(jetons) > 4 * MAPPAGES_MAX:
            break

    mappages: dict[int, str] = {}
    plages: list[tuple[int, int, int]] = []
    i = 0
    n = len(jetons)

    def hexs(debut: int, fin_mot: bytes) -> tuple[list[tuple[str, bytes]], int]:
        suite: list[tuple[str, bytes]] = []
        j = debut
        while j < n and not (jetons[j][0] == "mot" and jetons[j][1] == fin_mot):
            suite.append(jetons[j])
            j += 1
        return suite, j + 1

    while i < n and len(mappages) < MAPPAGES_MAX:
        genre, valeur = jetons[i]
        if genre != "mot":
            i += 1
            continue
        if valeur == b"begincodespacerange":
            suite, i = hexs(i + 1, b"endcodespacerange")
            paires = [v for g, v in suite if g == "hex"]
            for bas_h, haut_h in zip(paires[::2], paires[1::2], strict=False):
                bas_o, haut_o = _hex(bas_h), _hex(haut_h)
                if bas_o and haut_o and len(bas_o) == len(haut_o):
                    plages.append(
                        (
                            len(bas_o),
                            int.from_bytes(bas_o, "big"),
                            int.from_bytes(haut_o, "big"),
                        )
                    )
        elif valeur == b"beginbfchar":
            suite, i = hexs(i + 1, b"endbfchar")
            paires = [v for g, v in suite if g == "hex"]
            for src_h, dst_h in zip(paires[::2], paires[1::2], strict=False):
                src = _hex(src_h)
                if src:
                    mappages[int.from_bytes(src, "big")] = _texte_utf16(_hex(dst_h))
        elif valeur == b"beginbfrange":
            suite, i = hexs(i + 1, b"endbfrange")
            j = 0
            while j + 2 < len(suite):
                if suite[j][0] != "hex" or suite[j + 1][0] != "hex":
                    j += 1
                    continue
                bas_b, haut_b = _hex(suite[j][1]), _hex(suite[j + 1][1])
                if not bas_b or not haut_b:
                    j += 1
                    continue
                bas, haut = int.from_bytes(bas_b, "big"), int.from_bytes(haut_b, "big")
                haut = min(haut, bas + CODES_MAX_PAR_PLAGE - 1)
                if suite[j + 2][0] == "crochet" and suite[j + 2][1] == b"[":
                    k = j + 3
                    code = bas
                    while k < len(suite) and suite[k][0] == "hex" and code <= haut:
                        mappages[code] = _texte_utf16(_hex(suite[k][1]))
                        code += 1
                        k += 1
                    j = k + 1
                elif suite[j + 2][0] == "hex":
                    dst = _texte_utf16(_hex(suite[j + 2][1]))
                    for decalage in range(haut - bas + 1):
                        mappages[bas + decalage] = _incrementer(dst, decalage)
                        if len(mappages) >= MAPPAGES_MAX:
                            break
                    j += 3
                else:
                    j += 1
        else:
            i += 1
    return mappages, plages


