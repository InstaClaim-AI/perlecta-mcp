_ENCODAGES = {
    "/WinAnsiEncoding": ("cp1252", "winansi"),
    "/MacRomanEncoding": ("mac_roman", "macroman"),
    "/StandardEncoding": ("cp1252", "approx"),
    "/MacExpertEncoding": ("cp1252", "approx"),
}


def _nom(valeur: Any) -> str:
    try:
        return str(valeur)
    except Exception:
        return ""


def _nombre(valeur: Any, defaut: float = 0.0) -> float:
    try:
        return float(valeur)
    except (TypeError, ValueError, ArithmeticError):
        return defaut


def _largeurs_simples(dico: Any) -> dict[int, float]:
    largeurs: dict[int, float] = {}
    try:
        premier = int(dico.get("/FirstChar", 0))
        for index, valeur in enumerate(dico.get("/Widths", [])):
            if index > 256:
                break
            largeurs[premier + index] = _nombre(valeur) / 1000.0
    except Exception:
        pass
    return largeurs


def _largeurs_cid(descendant: Any) -> dict[int, float]:
    largeurs: dict[int, float] = {}
    try:
        w = list(descendant.get("/W", []))
    except Exception:
        return largeurs
    i = 0
    while i < len(w) and len(largeurs) < MAPPAGES_MAX:
        try:
            debut = int(_nombre(w[i]))
            if i + 1 < len(w) and not isinstance(w[i + 1], (int, float)) and _est_tableau(w[i + 1]):
                for index, valeur in enumerate(list(w[i + 1])[:CODES_MAX_PAR_PLAGE]):
                    largeurs[debut + index] = _nombre(valeur) / 1000.0
                i += 2
            elif i + 2 < len(w):
                fin = min(int(_nombre(w[i + 1])), debut + CODES_MAX_PAR_PLAGE)
                largeur = _nombre(w[i + 2]) / 1000.0
                for code in range(debut, fin + 1):
                    largeurs[code] = largeur
                i += 3
            else:
                break
        except Exception:
            break
    return largeurs


def _est_tableau(valeur: Any) -> bool:
    try:
        import pikepdf

        return isinstance(valeur, pikepdf.Array)
    except ImportError:  # pragma: no cover
        return isinstance(valeur, list)


def police_depuis(dico: Any, nom: str) -> Police:
    """Construit une Police depuis son dictionnaire. Ne leve jamais."""
    police = Police(nom=nom)
    try:
        return _police_depuis(dico, police)
    except Exception:
        return police


def _police_depuis(dico: Any, police: Police) -> Police:
    import pikepdf

    sous_type = _nom(dico.get("/Subtype", ""))
    base = _nom(dico.get("/BaseFont", ""))
    if "Courier" in base or "Mono" in base:
        police.largeur_defaut = 0.6

    if sous_type == "/Type0":
        police.octets_par_code = (2,)
        police.encodage = None
        police.decodage_defaut = "inconnu"
        descendants = dico.get("/DescendantFonts")
        if descendants is not None and len(descendants) > 0:
            descendant = descendants[0]
            police.largeurs = _largeurs_cid(descendant)
            police.largeur_defaut = _nombre(descendant.get("/DW", 1000), 1000.0) / 1000.0
    elif sous_type == "/Type3":
        police.type3 = True
        police.encodage = None
        police.decodage_defaut = "inconnu"
        matrice = [_nombre(v) for v in dico.get("/FontMatrix", [0.001, 0, 0, 0.001, 0, 0])]
        facteur = matrice[0] if matrice else 0.001
        police.largeurs = {c: w * 1000.0 * facteur for c, w in _largeurs_simples(dico).items()}
        police.largeur_defaut = 0.5
    else:
        encodage = dico.get("/Encoding")
        if isinstance(encodage, pikepdf.Name):
            police.encodage, police.decodage_defaut = _ENCODAGES.get(
                _nom(encodage), ("cp1252", "approx")
            )
        elif isinstance(encodage, pikepdf.Dictionary):
            police.encodage, police.decodage_defaut = _ENCODAGES.get(
                _nom(encodage.get("/BaseEncoding", "")), ("cp1252", "approx")
            )
            if "/Differences" in encodage:
                police.decodage_defaut = "approx"
        if base.split("+")[-1] in {"Symbol", "ZapfDingbats"}:
            police.decodage_defaut = "approx"
        police.largeurs = _largeurs_simples(dico) or largeurs_standard(base)
        descripteur = dico.get("/FontDescriptor")
        if descripteur is not None and "/MissingWidth" in descripteur:
            manquante = _nombre(descripteur.get("/MissingWidth")) / 1000.0
            if manquante > 0:
                police.largeur_defaut = manquante

    tounicode = dico.get("/ToUnicode")
    if isinstance(tounicode, pikepdf.Stream):
        mappages, plages = analyser_cmap(tounicode.read_bytes())
        if mappages:
            police.tounicode = mappages
            if plages:
                police.plages = tuple(plages)
                police.octets_par_code = tuple(sorted({nb for nb, _, _ in plages}))
            elif max(mappages) > 255:
                police.octets_par_code = (2,)
    return police
